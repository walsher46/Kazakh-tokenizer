def _retrieve_from_kb_dual(
    question: str,
    kb_q_emb: np.ndarray,
    kb_answers: list,
    threshold: float = 0.6,
):
    """
    Dual-view эмбеддинг арқылы Q→Q retrieval:
      - q_dual = _encode_retr([question])
      - sims  = kb_q_emb @ q_dual.T
    """
    qv = _encode_retr([question], normalize=True)   # [1, d]
    sims = (kb_q_emb @ qv.T).squeeze(1)            # [N]
    idx = int(np.argmax(sims))
    sim_val = float(sims[idx])
    if sim_val < threshold:
        return "Кешіріңіз, нақты жауап табылмады.", -1, sim_val
    return kb_answers[idx], idx, sim_val


def ask_question_runtime(question: str, threshold: float = 0.6):
    """
    Интерактив режим: толық QA базасынан dual-view Q→Q іздеу.
    """
    return _retrieve_from_kb_dual(
        question,
        kb_q_emb=qa_q_emb_dual,
        kb_answers=qa_answers_full,
        threshold=threshold,
    )


def ask_question_eval(question: str):
    """
    Held-out бағалау: TEST сұрағы → TRAIN KB (dual-view Q→Q).
    threshold=0.0 → reject жоқ, әрқашан ең жақын кандидат.
    """
    ans, idx, sim = _retrieve_from_kb_dual(
        question,
        kb_q_emb=train_q_emb_dual,
        kb_answers=train_answers,
        threshold=0.0,
    )
    return ans, idx, sim


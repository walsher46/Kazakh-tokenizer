def evaluate_accuracy_exact_femseg():
    """
    Accuracy@1 (Exact):
    Top-1 қайтарылған жауап true answer-мен жолдық деңгейде тең.
    """
    correct = 0
    total = len(test_questions)
    for q, true_a in zip(test_questions, test_answers):
        p, _, _ = ask_question_eval(q)
        if p.strip() == true_a.strip():
            correct += 1
    return correct / total if total > 0 else 0.0


def evaluate_cosine_similarity_femseg():
    """
    Average Cosine Similarity (EVAL):
    Freeze MiniLM эмбеддингтері бойынша орташа cosine(pred, true).
    """
    pv, tv = _encode_pairs_for_eval()
    pv = pv / np.linalg.norm(pv, axis=1, keepdims=True)
    tv = tv / np.linalg.norm(tv, axis=1, keepdims=True)
    cs = np.sum(pv * tv, axis=1)
    return float(np.mean(cs))


def evaluate_accuracy_semantic_cos_femseg(threshold: float = 0.85):
    """
    Accuracy@1 (Semantic Cosine ≥ threshold, EVAL модель):
    cosine(pred, true) ≥ threshold болса, сол жұп 'дұрыс' деп саналады.
    """
    pv, tv = _encode_pairs_for_eval()
    pv = pv / np.linalg.norm(pv, axis=1, keepdims=True)
    tv = tv / np.linalg.norm(tv, axis=1, keepdims=True)
    cs = np.sum(pv * tv, axis=1)
    return float(np.mean(cs >= threshold))


def evaluate_bert_score_and_semantic_femseg(
    threshold: float = 0.85,
    model_type: str = "xlm-roberta-large",
):
    """
    BERTScore (Precision / Recall / F1) және
    BERTScore F1 ≥ threshold бойынша семантикалық Accuracy@1.
    """
    preds, trues = [], []
    for q, true_a in zip(test_questions, test_answers):
        p, _, _ = ask_question_eval(q)
        preds.append(p)
        trues.append(true_a)

    P, R, F1 = bertscore(
        preds,
        trues,
        model_type=model_type,
        verbose=False,
        rescale_with_baseline=False,
        device=DEVICE,
    )

    sem_acc_bert = (F1 >= threshold).float().mean().item()

    return {
        "precision":         P.mean().item(),
        "recall":            R.mean().item(),
        "f1":                F1.mean().item(),
        "semantic_acc_bert": sem_acc_bert,
    }



def _encode_pairs_for_eval():
    """
    TEST жиыны үшін (predicted_answer, true_answer) жұптарының
    эмбеддингтерін EVAL модель арқылы есептеу.
    """
    preds, trues = [], []
    for q, true_a in zip(test_questions, test_answers):
        p, _, _ = ask_question_eval(q)
        preds.append(p)
        trues.append(true_a)

    pv = _encode_eval(preds,  normalize=False)
    tv = _encode_eval(trues, normalize=False)
    return pv, tv


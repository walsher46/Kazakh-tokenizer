def _encode_retr(texts, batch_size=32, normalize=True):
    """
    Retrieval үшін эмбеддинг (dual-view, эмбеддинг деңгейінде):
      - v_seg   = encode(FEMSeg_sp(text))
      - v_clean = encode(clean text)
      - v_dual  = ALPHA_SEG * v_seg + (1-ALPHA_SEG) * v_clean
    """
    texts = [str(t) for t in texts]
    texts_sp = [femseg_to_sp(t) for t in texts]

    with torch.inference_mode():
        # 1) segmented view
        v_seg = retr_model.encode(
            texts_sp,
            batch_size=batch_size,
            convert_to_numpy=True,
            normalize_embeddings=False,
        )

        # 2) clean view
        v_clean = retr_model.encode(
            texts,
            batch_size=batch_size,
            convert_to_numpy=True,
            normalize_embeddings=False,
        )

        vecs = ALPHA_SEG * v_seg + (1.0 - ALPHA_SEG) * v_clean

        if normalize:
            norms = np.linalg.norm(vecs, axis=1, keepdims=True) + 1e-12
            vecs = vecs / norms

    return vecs


def _encode_eval(texts, batch_size=32, normalize=False):
    """
    Бағалау үшін эмбеддинг (freeze MiniLM, segmentation-сыз).
    Мұнда таза сұрақ/жауап мәтіндері беріледі.
    """
    texts = [str(t) for t in texts]
    with torch.inference_mode():
        vecs = eval_model.encode(
            texts,
            batch_size=batch_size,
            convert_to_numpy=True,
            normalize_embeddings=normalize,
        )
    return vecs


class FEMSegV3(nn.Module):
    def __init__(
        self,
        vocab_size: int,
        char_emb_dim: int = 128,
        lstm_hidden_dim: int = 256,
        dropout: float = 0.3,
        num_tags: int = len(BMES_TAGS),
    ):
        super().__init__()

        self.emb = nn.Embedding(vocab_size, char_emb_dim, padding_idx=0)

        self.lstm = nn.LSTM(
            input_size=char_emb_dim,
            hidden_size=lstm_hidden_dim,
            num_layers=1,
            batch_first=True,
            bidirectional=True,
        )

        self.fc = nn.Linear(lstm_hidden_dim * 2, num_tags)
        self.crf = CRF(num_tags, batch_first=True)
        self.dropout = nn.Dropout(dropout)

    def forward_features(self, x: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
        emb = self.emb(x)
        emb = self.dropout(emb)
        h, _ = self.lstm(emb)
        h = self.dropout(h)
        return h

    def forward_logits(self, x: torch.Tensor, mask: torch.Tensor) -> torch.Tensor:
        feats = self.forward_features(x, mask)
        emissions = self.fc(feats)
        return emissions

    def forward(
        self,
        x: torch.Tensor,
        tags: torch.Tensor = None,
        mask: torch.Tensor = None,
    ):
        if mask is None:
            mask = x != 0

        emissions = self.forward_logits(x, mask)

        if tags is not None:
            loss = -self.crf(emissions, tags, mask=mask, reduction="mean")
            return loss

        best_paths = self.crf.decode(emissions, mask=mask)
        return best_paths


def bmes_to_cse(chars: List[str], tags: List[str]) -> str:
    morphs: List[str] = []
    cur = ""

    for ch, t in zip(chars, tags):
        if t == "B":
            if cur:
                morphs.append(cur)
            cur = ch
        elif t == "M":
            cur += ch
        elif t == "E":
            cur += ch
            morphs.append(cur)
            cur = ""
        elif t == "S":
            if cur:
                morphs.append(cur)
            morphs.append(ch)
            cur = ""

    if cur:
        morphs.append(cur)

    return "@@ ".join(morphs)


class KazMorphSegmentor:
    def __init__(
        self,
        char2id_path: str,
        ckpt_path: str,
        use_cuda: bool = True,
    ):
        with open(char2id_path, "r", encoding="utf-8") as f:
            self.char2id: Dict[str, int] = json.load(f)

        self.pad_id = 0
        self.unk_id = (
            self.char2id.get("<unk>")
            or self.char2id.get("[UNK]")
            or 1
        )

        self.device = torch.device(
            "cuda" if (use_cuda and torch.cuda.is_available()) else "cpu"
        )

        vocab_size = max(self.char2id.values()) + 1

        self.model = FEMSegV3(vocab_size=vocab_size)
        self.model.to(self.device)

        state = torch.load(ckpt_path, map_location=self.device)
        if isinstance(state, dict):
            if "state_dict" in state:
                state = state["state_dict"]
            elif "model_state_dict" in state:
                state = state["model_state_dict"]

        if isinstance(state, dict) and any(k.startswith("module.") for k in state.keys()):
            state = {k.replace("module.", "", 1): v for k, v in state.items()}

        self.model.load_state_dict(state, strict=True)
        self.model.eval()

    def _word_to_tensor(self, word: str):
        ids = [
            self.char2id.get(ch, self.unk_id)
            for ch in list(word)
        ]
        x = torch.tensor([ids], dtype=torch.long, device=self.device)
        mask = (x != self.pad_id)
        return x, mask

    def segment_word(self, word: str) -> str:
        word = word.strip()
        if not word:
            return ""

        x, mask = self._word_to_tensor(word)
        with torch.no_grad():
            best_paths = self.model(x, mask=mask)

        tag_ids = best_paths[0]
        tags = [ID2TAG[i] for i in tag_ids]

        return bmes_to_cse(list(word), tags)

    def segment_text(self, text: str) -> str:
        text = text.strip()
        if not text:
            return ""

        words = text.split()
        out_words: List[str] = []

        for w in words:
            seg_w = self.segment_word(w)
            out_words.append(seg_w)

        return " | ".join(out_words)


def femseg_to_sp(text: str) -> str:
    """
    FEMSeg_v3 → морфемалар → BPE-стильдегі '▁root suffix ...'
    Назар: бұл жерде SPM vocab қажет емес, тек мәтіндік белгілеу.
    """
    text = str(text).strip()
    if not text:
        return ""

    seg_line = femseg.segment_text(text)

    sp_tokens = []
    for word_seg in seg_line.split(" | "):
        word_seg = word_seg.strip()
        if not word_seg:
            continue

        morphs = [m.strip() for m in word_seg.split("@@ ") if m.strip()]
        if not morphs:
            continue

        sp_tokens.append("▁" + morphs[0])
        sp_tokens.extend(morphs[1:])

    return " ".join(sp_tokens)



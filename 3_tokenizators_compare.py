print("\n📦 [BASELINE-CLEAN] QA және TRAIN үшін CLEAN + SEGMENTED эмбеддингтерді есептеу...")
qa_q_emb_std_clean    = _encode_retr_std(qa_questions,  normalize=True, do_segment=False)
qa_q_emb_std_seg      = _encode_retr_std(qa_questions,  normalize=True, do_segment=True)
train_q_emb_std_clean = _encode_retr_std(train_questions, normalize=True, do_segment=False)
train_q_emb_std_seg   = _encode_retr_std(train_questions, normalize=True, do_segment=True)

ALPHA_SEG = 0.6  # dual-view салмағы: 0.6*seg + 0.4*clean (үш модельге де ортақ)

def _dual_view_sim_std(question: str,
                       kb_clean: np.ndarray,
                       kb_seg: np.ndarray) -> np.ndarray:
    """
    BASELINE-CLEAN dual-view similarity:
    - clean view: original text
    - segmented view: SPM сегменттелген text
    Екі view қосылып, ортақ скора есептеледі.
    """
    q_clean = _encode_retr_std([question], normalize=True, do_segment=False)
    q_seg   = _encode_retr_std([question], normalize=True, do_segment=True)

    sims_clean = (kb_clean @ q_clean.T).squeeze(1)
    sims_seg   = (kb_seg   @ q_seg.T).squeeze(1)

    sims = ALPHA_SEG * sims_seg + (1.0 - ALPHA_SEG) * sims_clean
    return sims

def ask_question_std(question, threshold=0.6):
    """
    BASELINE-CLEAN: интерактив режим (full QA KB, dual-view Q→Q).
    """
    sims = _dual_view_sim_std(
        question,
        kb_clean=qa_q_emb_std_clean,
        kb_seg=qa_q_emb_std_seg
    )
    idx = int(np.argmax(sims))
    if float(sims[idx]) < threshold:
        return "Кешіріңіз, нақты жауап табылмады.", -1
    return qa_answers[idx], idx

def ask_question_eval_std(question):
    """
    BASELINE-CLEAN: held-out бағалау (TEST Q → TRAIN KB, dual-view Q→Q).
    """
    sims = _dual_view_sim_std(
        question,
        kb_clean=train_q_emb_std_clean,
        kb_seg=train_q_emb_std_seg
    )
    idx = int(np.argmax(sims))
    return train_answers[idx], idx

def _encode_pairs_for_eval_std():
    preds, trues = [], []
    for q, true_a in zip(test_questions, test_answers):
        p, _ = ask_question_eval_std(q)
        preds.append(p)
        trues.append(true_a)
    pv = _encode_eval(preds,  normalize=False)
    tv = _encode_eval(trues, normalize=False)
    return pv, tv

def evaluate_accuracy_exact_std():
    correct = 0
    total = len(test_questions)
    for q, true_a in zip(test_questions, test_answers):
        p, _ = ask_question_eval_std(q)
        if p.strip() == true_a.strip():
            correct += 1
    return correct / total if total > 0 else 0.0

def evaluate_cosine_similarity_std():
    pv, tv = _encode_pairs_for_eval_std()
    pv = pv / np.linalg.norm(pv, axis=1, keepdims=True)
    tv = tv / np.linalg.norm(tv, axis=1, keepdims=True)
    cs = np.sum(pv * tv, axis=1)
    return float(np.mean(cs))

def evaluate_accuracy_semantic_cos_std(threshold=0.85):
    pv, tv = _encode_pairs_for_eval_std()
    pv = pv / np.linalg.norm(pv, axis=1, keepdims=True)
    tv = tv / np.linalg.norm(tv, axis=1, keepdims=True)
    cs = np.sum(pv * tv, axis=1)
    return float(np.mean(cs >= threshold))

def evaluate_bert_score_and_semantic_std(threshold=0.85, model_type="xlm-roberta-large"):
    preds, trues = [], []
    for q, true_a in zip(test_questions, test_answers):
        p, _ = ask_question_eval_std(q)
        preds.append(p)
        trues.append(true_a)

    P, R, F1 = bertscore(
        preds,
        trues,
        model_type=model_type,
        verbose=False,
        rescale_with_baseline=False,
        device=DEVICE,
    )

    sem_acc_bert = (F1 >= threshold).float().mean().item()

    return {
        "precision": P.mean().item(),
        "recall":    R.mean().item(),
        "f1":        F1.mean().item(),
        "semantic_acc_bert": sem_acc_bert,
    }

def evaluate_system_std():
    t0 = time.time()

    acc_exact   = evaluate_accuracy_exact_std()

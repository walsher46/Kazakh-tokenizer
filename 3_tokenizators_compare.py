# --- Жаңа Kazakh токендердің эмбеддингін мағыналы инициализациялау ---
auto_model_kz = word_embedding_model_kz.auto_model
emb_layer_kz = auto_model_kz.get_input_embeddings()

with torch.no_grad():
    weight_kz = emb_layer_kz.weight.data
    old_vocab_size = orig_vocab_size            # алғашқы бөлігін оригинал деп аламыз
    new_vocab_size = len(kk_tok)

    # Оригинал токендердің орташа нормасын есептейміз
    base_norms = weight_kz[:old_vocab_size].norm(dim=1)
    avg_norm = base_norms.mean().item()
    print(f"🔧 [KAZ] Жаңа токен эмбеддингтерін инициализациялау: {old_vocab_size} → {new_vocab_size}")
    print(f"🔧 [KAZ] Оригинал эмбеддинг нормаларының орташа мәні: {avg_norm:.4f}")

    for new_id in range(old_vocab_size, new_vocab_size):
        idx_in_new = new_id - old_vocab_size
        if idx_in_new < 0 or idx_in_new >= len(new_pieces):
            continue

        piece = new_pieces[idx_in_new]         # мысалы: '▁Бағдарлама@@'
        # SPM piece → адамша текст
        piece_text = piece.replace("▁", " ").strip()
        if not piece_text:
            continue

        # 1) piece_text-ті стандартты токенизатормен токенизациялау
        base_ids = base_tok(
            piece_text,
            add_special_tokens=False
        )["input_ids"]
        base_ids = [i for i in base_ids if i < old_vocab_size]

        # 2) Егер бәрібір бос болса – символ деңгей fall-back
        if len(base_ids) == 0:
            chars = list(piece_text)
            for ch in chars:
                ids_ch = base_tok(ch, add_special_tokens=False)["input_ids"]
                base_ids.extend([i for i in ids_ch if i < old_vocab_size])

        if len(base_ids) == 0:
            # ешқандай мәнді mapping шықпаса, моделдің random init-ін қалдырамыз
            continue

        # 3) Претренед эмбеддингтерінің орташа мәні
        base_vec = weight_kz[base_ids].mean(dim=0)

        # 4) Нормасын оригинал орташа нормаға келтіру (distribution alignment)
        vec_norm = base_vec.norm().item()
        if vec_norm > 0:
            base_vec = base_vec / vec_norm * avg_norm

        weight_kz[new_id] = base_vec

print("✅ Жаңа Kazakh токендер pretrained эмбеддингтерден (мағыналы схема) инициализацияланды.")

pooling_model_kz = models.Pooling(
    word_embedding_model_kz.get_word_embedding_dimension(),
    pooling_mode_mean_tokens=True,
    pooling_mode_cls_token=False,
    pooling_mode_max_tokens=False,
)


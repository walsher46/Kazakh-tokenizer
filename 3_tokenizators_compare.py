sp = spm.SentencePieceProcessor()
sp.Load(spm_model_path)

def segment_text(text: str) -> str:
    """
    Kazakh SPM-ге негізделген субсөздік/морфологиялық сегментация.
    Нәтиже – SPM pieces бос орынмен бөлінген string.
    Бұл функция dual-view үшін БАРЛЫҚ модельде (BASELINE, KAZ, mT5) қолданылады.
    """
    if not isinstance(text, str):
        text = str(text)
    pieces = sp.encode_as_pieces(text)
    return " ".join(pieces)

# 1. Unigram вокабы: әуелі ОРИГИНАЛ токендер (дәл сол id тәртібімен)
vocab = []
for idx in range(orig_vocab_size):
    tok_str = inv_base_vocab.get(idx, None)
    if tok_str is None:
        tok_str = f"[UNUSED_{idx}]"
    vocab.append((tok_str, 0.0))  # score маңызды емес, тек салыстырмалы

# 2. SPM вокабынан ЖАҢА токендерді ғана үстінен қосамыз
get_score = getattr(sp, "GetScore", None)
spm_size = sp.GetPieceSize()
added = 0
new_pieces = []       # жаңа SPM токендердің реті (id mapping үшін)

for i in range(spm_size):
    piece = sp.IdToPiece(i)
    if piece in base_vocab:
        continue
    score = float(get_score(i)) if callable(get_score) else -1.0
    vocab.append((piece, score))
    new_pieces.append(piece)
    added += 1

print(f"➕ SPM-нен қосылған жаңа токендер саны: {added}")
print("🔢 Жаңа Unigram вокабының өлшемі:", len(vocab))

# 3. UNK id – оригинал токенизатордан
if base_tok.unk_token_id is not None:
    unk_id = base_tok.unk_token_id
else:
    unk_id = next(
        i for i, (t, _) in enumerate(vocab) if t in ("<unk>", "[UNK]")
    )

# 4. Unigram моделі
tok = Tokenizer(Unigram(vocab=vocab, unk_id=unk_id))

# 5. PreTokenizer/Decoder – мүмкін болса, оригинал backend-тен
backend = getattr(base_tok, "backend_tokenizer", None)
if backend is not None:
    if backend.normalizer is not None:
        tok.normalizer = backend.normalizer
    tok.pre_tokenizer = backend.pre_tokenizer
    tok.decoder = backend.decoder
else:
    try:
        tok.pre_tokenizer = PreMS("▁")
    except TypeError:
        tok.pre_tokenizer = PreMS()
    try:
        tok.decoder = DecMS("▁")
    except TypeError:
        tok.decoder = DecMS()

# 6. Арнайы токендер – оригиналдан
cls_tok = base_tok.cls_token or "[CLS]"
sep_tok = base_tok.sep_token or "[SEP]"
pad_tok = base_tok.pad_token or "[PAD]"
mask_tok = base_tok.mask_token or "[MASK]"
unk_tok_str = base_tok.unk_token or "<unk>"

tok.post_processor = TemplateProcessing(
    single=f"{cls_tok} $A {sep_tok}",
    pair=f"{cls_tok} $A {sep_tok} $B {sep_tok}",
    special_tokens=[
        (cls_tok, base_vocab[cls_tok]),
        (sep_tok, base_vocab[sep_tok]),
    ],
)

kk_tok = PreTrainedTokenizerFast(
    tokenizer_object=tok,
    unk_token=unk_tok_str,
    sep_token=sep_tok,
    pad_token=pad_tok,
    cls_token=cls_tok,
    mask_token=mask_tok,
)
kk_tok.model_max_length = getattr(base_tok, "model_max_length", 512)

print("✅ Kazakh Fast токенизатор дайын. Vocab size:", len(kk_tok))

kk_tok.save_pretrained(KK_TOK_DIR)
print("📝 Kazakh токенизатор файлдары жазылды →", KK_TOK_DIR)

print("⬇️ MiniLM encoder-ін жүктеу және Kazakh токенизаторымен байланыстыру:", SENTENCE_T_NAME)

word_embedding_model_kz = models.Transformer(
    SENTENCE_T_NAME,
    tokenizer_name_or_path=KK_TOK_DIR
)

# Вокаб өлшемін жаңа Kazakh токенизаторға бейімдеу
